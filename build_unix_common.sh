#!/usr/bin/env bash
# Shared build steps for Linux and macOS (called by build_linux.sh and build_macos.command).
# Creates a fresh virtual environment, installs the libraries, runs the tests and builds
# both programs with PyInstaller.  Full log: build_log.txt
set -u
cd "$(dirname "$0")"
LOG="$PWD/build_log.txt"
echo "Build started $(date)" > "$LOG"

fail() {
  echo
  echo "BUILD FAILED: $1"
  echo "Last lines of build_log.txt:"
  echo "----------------------------------------------------------------------------"
  tail -n 25 "$LOG"
  echo "----------------------------------------------------------------------------"
  echo "Send build_log.txt to get help."
  exit 1
}

echo "[0/6] Removing files generated by a previous build or copied from another PC..."
rm -rf .venv build dist .pytest_cache
find . -name __pycache__ -type d -prune -exec rm -rf {} + 2>/dev/null

echo "[1/6] Checking Python..."
PY=""
for cand in python3.15 python3.14 python3.13 python3.12 python3.11 python3.10 python3; do
  if command -v "$cand" >/dev/null 2>&1 && "$cand" -c 'import sys, struct; sys.exit(0 if (3, 10) <= sys.version_info[:2] <= (3, 15) and struct.calcsize("P") == 8 else 1)' 2>/dev/null; then
    PY="$cand"; break
  fi
done
[ -n "$PY" ] || fail "Python 3.10 to 3.15 (64-bit) not found. Install it from python.org (macOS) or your package manager (Linux)."
"$PY" -c 'import sys; print("  Python", sys.version.split()[0])'
"$PY" -c 'import venv, ensurepip' 2>/dev/null || fail "The Python 'venv' module is missing (Linux: sudo apt install python3-venv)."

echo "[2/6] Creating a fresh virtual environment..."
"$PY" -m venv .venv >> "$LOG" 2>&1 || fail "could not create the virtual environment"
VPY=".venv/bin/python"

echo "[3/6] Installing the libraries (a few minutes, needs internet)..."
"$VPY" -m pip install --upgrade pip >> "$LOG" 2>&1 || fail "pip upgrade"
"$VPY" -m pip install -r requirements.txt >> "$LOG" 2>&1 || fail "library installation"

echo "[4/6] Running the automated tests..."
QT_QPA_PLATFORM=offscreen "$VPY" -m pytest -q -p no:cacheprovider tests >> "$LOG" 2>&1 || fail "automated tests"

echo "[5/6] Building ENS_Image_Database..."
"$VPY" -m PyInstaller --noconfirm --clean ens_database.spec >> "$LOG" 2>&1 || fail "ENS_Image_Database build"
echo "[6/6] Building Spectral_Analyzer..."
"$VPY" -m PyInstaller --noconfirm --clean spectral_analyzer.spec >> "$LOG" 2>&1 || fail "Spectral_Analyzer build"
rm -rf build
echo "Build finished."
